<?php

namespace App\Controllers\Tour;

use App\Controllers\BaseController;
use App\Libraries\MenuLoader;

class TourTimelineController extends BaseController
{
    protected $db;

    public function __construct()
    {
        $this->db = \Config\Database::connect();
    }

    public function index()
    {
        // Validate tour_id parameter
        $tour_id = $this->request->getGet('tour_id');

        if (!$tour_id) {
            return redirect()->back()->with('error', 'Tour ID is required');
        }

        // Get tour basic information
        $tour_info = $this->getTourInfo($tour_id);

        if (!$tour_info) {
            return redirect()->back()->with('error', 'Tour not found');
        }

        // Build timeline steps
        $steps = [];

        // Step 1: Quotation Creation
        $steps[] = $this->getQuotationData($tour_id, $tour_info);

        // Step 2: Tour Confirmation (Invoice Generation)
        $steps[] = $this->getInvoiceData($tour_id);

        // Step 3a: Hotel Reservation
        $steps[] = $this->getHotelReservationData($tour_id);

        // Step 3b: Driver Advance Payment (includes Shop Allocation as branch)
        $steps[] = $this->getDriverAdvanceData($tour_id);

        // Load menu data using the custom library
        $menuLoader = new MenuLoader();
        $data = $menuLoader->loadMenuData();

        $data['tour_info'] = $tour_info;
        $data['steps'] = $steps;

        return view('pages/tour/tour_timeline', $data);
    }

    private function getTourInfo($tour_id)
    {
        $query = $this->db->query(
            "SELECT tour_id, manual_id, consignee AS tour_name,
                    start_date, end_date, create_user, create_time
             FROM consignee
             WHERE tour_id = ?",
            [$tour_id]
        );

        return $query->getRow();
    }

    private function getQuotationData($tour_id, $tour_info)
    {
        $status = 'completed'; // Always completed if tour exists

        return [
            'step_number' => 1,
            'name' => 'Quotation Creation',
            'icon_class' => 'file-text',
            'status' => $status,
            'main_data' => [
                'label' => 'Created By',
                'value' => $tour_info->create_user ?? 'N/A',
                'timestamp' => $tour_info->create_time ?? null
            ],
            'sub_data' => [
                ['label' => 'Manual ID', 'value' => $tour_info->manual_id ?? 'N/A'],
                ['label' => 'Tour ID', 'value' => $tour_info->tour_id ?? 'N/A'],
                ['label' => 'Tour Name', 'value' => $tour_info->tour_name ?? 'N/A']
            ]
        ];
    }

    private function getInvoiceData($tour_id)
    {
        $query = $this->db->query(
            "SELECT dil.invoice_no, dil.date AS invoice_date,
                    dil.credit_balance AS total_amount,
                    ar.Cashier AS generated_by, ar.Dt AS generated_at
             FROM debtor_invoice_log dil
             LEFT JOIN account_runing ar ON ar.Invoice_Num = dil.invoice_no AND ar.Dr > 0
             WHERE dil.tour_id = ?
             ORDER BY ar.Dt ASC
             LIMIT 1",
            [$tour_id]
        );

        $result = $query->getRow();

        $status = $result && $result->generated_by ? 'completed' : 'not_started';

        $main_data = [
            'label' => 'Generated By',
            'value' => $result->generated_by ?? 'Not generated',
            'timestamp' => $result->invoice_date ?? null
        ];

        $sub_data = [];
        if ($result && $result->invoice_no) {
            $sub_data = [
                ['label' => 'Invoice Number', 'value' => $result->invoice_no],
                // ['label' => 'Total Amount', 'value' => 'LKR ' . number_format($result->total_amount, 2)]
            ];
        }

        return [
            'step_number' => 2,
            'name' => 'Tour Confirmation',
            'icon_class' => 'check-circle-fill',
            'status' => $status,
            'main_data' => $main_data,
            'sub_data' => $sub_data
        ];
    }

    private function getHotelReservationData($tour_id)
    {
        // Get invoice acceptance data (Stage 1) and payment request data
        $consigneeQuery = $this->db->query(
            "SELECT accepted_user, accepted_date, inv_alert_status,
                    payment_request, payment_request_user, payment_request_date
             FROM consignee
             WHERE tour_id = ?",
            [$tour_id]
        );
        $consignee = $consigneeQuery->getRow();

        // Get all hotels for this tour (non-empty hotel_acc) with hotel names
        $hotelsQuery = $this->db->query(
            "SELECT hotel_name, hotel_acc, booking_confirmed_flag, hotel_payment_flag, hotel_advance, confirmation_reference
             FROM tour_quotations
             WHERE quotation_id = ?
               AND hotel_acc IS NOT NULL
               AND TRIM(hotel_acc) != ''
               AND hotel_acc != '0'
             GROUP BY hotel_acc",
            [$tour_id]
        );
        $hotels = $hotelsQuery->getResult();

        // Get accounting entries (Stage 2 indicator)
        $accountingQuery = $this->db->query(
            "SELECT Cashier, Dt
             FROM account_runing
             WHERE index_no = ? AND advances_pay = 22
             ORDER BY Dt DESC
             LIMIT 1",
            [$tour_id]
        );
        $accounting = $accountingQuery->getRow();

        // Get voucher/payment data (Stage 3 indicator)
        $voucherQuery = $this->db->query(
            "SELECT login AS paid_by, W_Date,
                    Aut_user, aut_date, Aflag
             FROM voucher
             WHERE ref_po = ? AND advances_pay = 2
             ORDER BY W_Date DESC
             LIMIT 1",
            [$tour_id]
        );
        $voucher = $voucherQuery->getRow();

        // Determine stages completion
        $status = 'not_started';
        $stage_info = '';
        $stages_complete = 0;

        // Stage 1: Invoice Accepted
        $stage1_complete = ($consignee && $consignee->accepted_user) ? true : false;

        // Stage 2: ALL hotels booking confirmed + accounting entries exist
        $stage2_complete = false;
        if (count($hotels) > 0 && $accounting) {
            $all_confirmed = true;
            foreach ($hotels as $hotel) {
                if ($hotel->booking_confirmed_flag != 1) {
                    $all_confirmed = false;
                    break;
                }
            }
            $stage2_complete = $all_confirmed;
        }

        // Stage 3: ALL hotels payment done
        $stage3_complete = false;
        if (count($hotels) > 0) {
            $all_paid = true;
            foreach ($hotels as $hotel) {
                if ($hotel->hotel_payment_flag != 1) {
                    $all_paid = false;
                    break;
                }
            }
            $stage3_complete = $all_paid;
        }

        // Primary stages: Booking Confirmation (Stage 1) and Payment (Stage 2)
        // Invoice acceptance is optional and tracked separately
        if ($stage3_complete) {
            $status = 'completed';
            $stages_complete = 2;
            $stage_info = 'Booking confirmed and paid';
        } elseif ($stage2_complete) {
            $status = 'in_progress';
            $stages_complete = 1;
            $stage_info = 'Booking confirmed, payment pending';
        } elseif (count($hotels) > 0) {
            // Hotels exist but not confirmed
            $status = 'in_progress';
            $stages_complete = 0;
            $stage_info = 'Hotels allocated, confirmation pending';
        }

        // Determine main data based on highest completed action
        $main_label = 'Not started';
        $main_value = 'Not started';
        $main_timestamp = null;

        if ($stage3_complete && $voucher) {
            $main_label = 'Payment By';
            $main_value = $voucher->paid_by;
            $main_timestamp = $voucher->W_Date;
        } elseif ($stage2_complete && $accounting) {
            $main_label = 'Confirmed By';
            $main_value = $accounting->Cashier;
            $main_timestamp = $accounting->Dt;
        } elseif ($stage1_complete && $consignee) {
            $main_label = 'Accepted By';
            $main_value = $consignee->accepted_user;
            $main_timestamp = $consignee->accepted_date;
        }

        $main_data = [
            'label' => $main_label,
            'value' => $main_value,
            'timestamp' => $main_timestamp
        ];

        // Build sub_data - only essential details
        $sub_data = [];
        if (count($hotels) > 0 || $stage1_complete) {
            // Calculate total advance
            if ($stage2_complete && count($hotels) > 0) {
                $total_advance = array_sum(array_column($hotels, 'hotel_advance'));
                $sub_data[] = ['label' => 'Total Hotel Advance', 'value' => 'LKR ' . number_format($total_advance, 2)];
            }

            $sub_data[] = ['label' => 'Hotels Count', 'value' => count($hotels)];
            $sub_data[] = ['label' => 'Status', 'value' => $stage_info];
        }

        // Build stage branches for visual timeline
        $stage_branches = [];

        // Branch 1: Invoice Accepted (from consignee table)
        $stage_branches[] = [
            'title' => 'Invoice Accepted',
            'user' => $stage1_complete ? ($consignee->accepted_user ?? 'N/A') : 'Pending',
            'timestamp' => $stage1_complete ? ($consignee->accepted_date ?? null) : null,
            'completed' => $stage1_complete
        ];

        // Branch 2: Booking Confirmation
        $stage_branches[] = [
            'title' => 'Booking Confirmed',
            'user' => $stage2_complete ? ($accounting->Cashier ?? 'N/A') : 'Pending',
            'timestamp' => $stage2_complete ? ($accounting->Dt ?? null) : null,
            'completed' => $stage2_complete
        ];

        // Branch 3: Payment
        $stage_branches[] = [
            'title' => 'Payment Done',
            'user' => $stage3_complete ? ($voucher->paid_by ?? 'N/A') : 'Pending',
            'timestamp' => $stage3_complete ? ($voucher->W_Date ?? null) : null,
            'completed' => $stage3_complete
        ];

        // Branch 4: Voucher Authentication
        $voucher_authenticated = ($voucher && $voucher->Aflag == 1) ? true : false;
        $stage_branches[] = [
            'title' => 'Voucher Authenticated',
            'user' => $voucher_authenticated ? ($voucher->Aut_user ?? 'N/A') : 'Pending',
            'timestamp' => $voucher_authenticated ? ($voucher->aut_date ?? null) : null,
            'completed' => $voucher_authenticated
        ];

        return [
            'step_number' => 3,
            'name' => 'Hotel Reservation',
            'icon_class' => 'building',
            'status' => $status,
            'main_data' => $main_data,
            'sub_data' => $sub_data,
            'stage_info' => $stage_info,
            'hotels' => $hotels,  // Pass hotels data for grid display
            'stage_branches' => $stage_branches  // Pass stage branches for timeline visualization
        ];
    }

    private function getDriverAdvanceData($tour_id)
    {
        $query = $this->db->query(
            "SELECT dar.amount AS requested_amount, dar.username AS requested_by,
                    dar.date AS request_date, dar.flag AS request_status,
                    pr.requestAmount AS approved_amount,
                    pr.payment_request_user AS authenticated_by,
                    pr.payment_request_date AS authentication_date,
                    ar.Dr AS paid_amount, ar.Date AS payment_date,
                    ar.Dt AS payment_timestamp
             FROM driver_advance_request dar
             LEFT JOIN payment_request pr ON pr.tour_id = dar.tour_id AND pr.hotel_acc = dar.driver
             LEFT JOIN account_runing ar ON ar.index_no = dar.tour_id AND ar.L_Code = dar.driver AND ar.Dr > 0
             WHERE dar.tour_id = ?
             ORDER BY dar.date DESC
             LIMIT 1",
            [$tour_id]
        );

        $result = $query->getRow();

        // Get shop allocation data
        $shopQuery = $this->db->query(
            "SELECT COUNT(*) as shop_count,
                    MIN(allocated_by) as allocated_by,
                    MIN(created_at) as first_allocation_date,
                    MAX(created_at) as last_allocation_date
             FROM tour_shop_allocation
             WHERE tour_id = ?
             GROUP BY tour_id",
            [$tour_id]
        );
        $shopResult = $shopQuery->getRow();

        // Get voucher authentication for driver advance
        $voucherAuthQuery = $this->db->query(
            "SELECT Aut_user, aut_date, Aflag
             FROM voucher
             WHERE C_Number = ? AND advances_pay = 1 AND Aflag = 1
             ORDER BY aut_date DESC
             LIMIT 1",
            [$tour_id]
        );
        $voucherAuth = $voucherAuthQuery ? $voucherAuthQuery->getRow() : null;

        // Determine status based on stages
        $status = 'not_started';
        $stage_info = '';

        if ($result) {
            if ($result->paid_amount && $result->payment_date) {
                $status = 'completed';
                $stage_info = 'All 3 stages complete';
            } elseif ($result->authenticated_by) {
                $status = 'in_progress';
                $stage_info = 'Stage 2 of 3 complete (Authenticated)';
            } elseif ($result->requested_by) {
                $status = 'in_progress';
                $stage_info = 'Stage 1 of 3 complete (Requested)';
            }
        }

        $main_data = [
            'label' => 'Latest Action By',
            'value' => $result->requested_by ?? 'Not started',
            'timestamp' => $result->payment_timestamp ?? $result->authentication_date ?? $result->request_date ?? null
        ];

        $sub_data = [];
        if ($result && $result->requested_by) {
            $sub_data[] = ['label' => 'Status', 'value' => $stage_info];
            $sub_data[] = ['label' => 'Requested By', 'value' => $result->requested_by];
            $sub_data[] = ['label' => 'Requested Amount', 'value' => 'LKR ' . number_format($result->requested_amount, 2)];

            if ($result->authenticated_by) {
                $sub_data[] = ['label' => 'Authenticated By', 'value' => $result->authenticated_by];
                $sub_data[] = ['label' => 'Approved Amount', 'value' => 'LKR ' . number_format($result->approved_amount, 2)];
            }

            if ($result->paid_amount) {
                $sub_data[] = ['label' => 'Paid Amount', 'value' => 'LKR ' . number_format($result->paid_amount, 2)];
                $sub_data[] = ['label' => 'Payment Date', 'value' => $result->payment_date];
            }
        }

        // Build stage branches for visual timeline
        $stage_branches = [];

        // Branch 1: Driver Advance Requested
        $advance_requested = ($result && $result->requested_by) ? true : false;
        $stage_branches[] = [
            'title' => 'Advance Requested',
            'user' => $advance_requested ? ($result->requested_by ?? 'N/A') : 'Pending',
            'timestamp' => $advance_requested ? ($result->request_date ?? null) : null,
            'completed' => $advance_requested
        ];

        // Branch 2: Driver Advance Authenticated
        $advance_authenticated = ($result && $result->authenticated_by) ? true : false;
        $stage_branches[] = [
            'title' => 'Advance Authenticated',
            'user' => $advance_authenticated ? ($result->authenticated_by ?? 'N/A') : 'Pending',
            'timestamp' => $advance_authenticated ? ($result->authentication_date ?? null) : null,
            'completed' => $advance_authenticated
        ];

        // Branch 3: Driver Advance Paid
        $advance_paid = ($result && $result->paid_amount) ? true : false;
        $stage_branches[] = [
            'title' => 'Advance Paid',
            'user' => $advance_paid ? 'N/A' : 'Pending',
            'timestamp' => $advance_paid ? ($result->payment_timestamp ?? null) : null,
            'completed' => $advance_paid
        ];

        // Branch 4: Shop Allocation
        $shop_allocated = ($shopResult && $shopResult->shop_count > 0) ? true : false;
        $stage_branches[] = [
            'title' => 'Shop Allocated',
            'user' => $shop_allocated ? ($shopResult->allocated_by ?? 'N/A') : 'Pending',
            'timestamp' => $shop_allocated ? ($shopResult->first_allocation_date ?? null) : null,
            'completed' => $shop_allocated
        ];

        // Branch 5: Voucher Authentication
        $voucher_authenticated = ($voucherAuth && !empty($voucherAuth->Aut_user)) ? true : false;
        $stage_branches[] = [
            'title' => 'Voucher Authenticated',
            'user' => $voucher_authenticated ? ($voucherAuth->Aut_user ?? 'N/A') : 'Pending',
            'timestamp' => $voucher_authenticated ? ($voucherAuth->aut_date ?? null) : null,
            'completed' => $voucher_authenticated
        ];

        return [
            'step_number' => 4,
            'name' => 'Driver Advance Payment',
            'icon_class' => 'cash-coin',
            'status' => $status,
            'main_data' => $main_data,
            'sub_data' => $sub_data,
            'stage_info' => $stage_info,
            'stage_branches' => $stage_branches
        ];
    }

    private function getShopAllocationData($tour_id)
    {
        $query = $this->db->query(
            "SELECT COUNT(*) as shop_count,
                    MIN(allocated_by) as allocated_by,
                    MIN(created_at) as first_allocation_date,
                    MAX(created_at) as last_allocation_date
             FROM tour_shop_allocation
             WHERE tour_id = ?
             GROUP BY tour_id",
            [$tour_id]
        );

        $result = $query->getRow();

        $status = $result && $result->shop_count > 0 ? 'completed' : 'not_started';

        $main_data = [
            'label' => 'Allocated By',
            'value' => $result->allocated_by ?? 'Not allocated',
            'timestamp' => $result->first_allocation_date ?? null
        ];

        $sub_data = [];
        if ($result && $result->shop_count > 0) {
            $sub_data = [
                ['label' => 'Total Shops', 'value' => $result->shop_count],
                ['label' => 'First Allocation', 'value' => $result->first_allocation_date],
                ['label' => 'Last Allocation', 'value' => $result->last_allocation_date]
            ];
        }

        return [
            'step_number' => 5,
            'name' => 'Shop Allocation',
            'icon_class' => 'shop',
            'status' => $status,
            'main_data' => $main_data,
            'sub_data' => $sub_data
        ];
    }
}
